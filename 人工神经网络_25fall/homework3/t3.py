def WTA2(x, w):
    """ 
    Win-Take-All (赢者通吃): 找到距离最小的神经元
    """
    # 计算欧氏距离的平方 (曼哈顿距离或欧氏距离均可用于竞争，原代码中使用点积模拟平方欧氏距离)
    # dist = np.array([(x-ww).dot(x-ww) for ww in w]) # Original implementation using dot
    dist = np.sum((x - w)**2, axis=1) # Standard numpy implementation of squared Euclidean distance
    
    return np.argmin(dist)

# --- 0D 拓扑：仅更新获胜节点 ---
def compete0(x_dataset, w, eta):
    """
    0D Competitive Learning (Winner-Take-All)
    """
    for xx in x_dataset:
        id = WTA2(xx, w)
        # 权重更新规则: w_new = w_old + eta * (x - w_old)
        w[id] = w[id] + eta * (xx - w[id])
    return w

# --- 1D 拓扑：更新获胜节点和线性邻居 ---
def compete1(x_dataset, w, eta):
    """
    1D Competitive Learning (Winner and Immediate Neighbors)
    """
    for xx in x_dataset:
        id = WTA2(xx, w)
        
        # 1. 更新获胜节点
        w[id] = w[id] + eta * (xx - w[id])

        # 2. 更新左邻居 (如果存在)
        if id > 0:
            w[id-1] = w[id-1] + eta * (xx - w[id-1])

        # 3. 更新右邻居 (如果存在)
        if id + 1 < w.shape[0]:
            w[id+1] = w[id+1] + eta * (xx - w[id+1])
            
    return w

# --- 2D 拓扑：获取平面邻居 ---
def neighborid2(id, row, col):
    """
    获取 5x5 网格中获胜节点 'id' 的直接邻居 (上下左右)
    """
    rown = id // col
    coln = id % col

    iddim = [id] # 包含自身

    # 左邻居
    if coln > 0:        iddim.append(id - 1)
    # 右邻居
    if coln < col - 1:    iddim.append(id + 1)
    # 上邻居
    if rown > 0:        iddim.append(id - col)
    # 下邻居
    if rown < row - 1:    iddim.append(id + col)

    return iddim

# --- 2D 拓扑：更新获胜节点和平面邻居 ---
def compete2(x_dataset, w, eta):
    """
    2D Self-Organizing Map (Winner and Planar Neighbors)
    """
    for xx in x_dataset:
        id = WTA2(xx, w) # 获胜节点

        # 获取邻域索引 (5x5 网格)
        iddim = neighborid2(id, 5, 5)

        # 更新获胜节点和邻域节点的权重
        for iidd in iddim:
            w[iidd] = w[iidd] + eta * (xx - w[iidd])

    return w

